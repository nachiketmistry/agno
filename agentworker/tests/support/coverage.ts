/**
 * Operation coverage report. Run the suites against the Python reference with
 * AGENTWORKER_COVERAGE_FILE set, then run this script on the same file. It lists, for
 * every contract operation, whether a test got a successful (2xx) answer from it, and
 * fails if an operation is neither exercised successfully nor listed in
 * `coverage-exemptions.json` with a reason.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { matchOperation, operations } from "@agentworker/contract";
import exemptions from "../coverage-exemptions.json";

const file = process.env.AGENTWORKER_COVERAGE_FILE;
if (!file) throw new Error("Set AGENTWORKER_COVERAGE_FILE to the request log the suites wrote");

const keys = operations.map((operation) => `${operation.method} ${operation.path}`);
const success = new Set<string>();
const seen = new Set<string>();
for (const line of readFileSync(file, "utf8").split("\n").filter(Boolean)) {
  const [method, path, status] = line.split(" ") as [string, string, string];
  const operation = matchOperation(method, path);
  if (!operation) continue;
  const key = `${operation.method} ${operation.path}`;
  seen.add(key);
  if (status.startsWith("2")) success.add(key);
}

const exempt = exemptions as Record<string, string>;
const rows = keys.map((key) => ({
  key,
  state: success.has(key)
    ? "success path tested"
    : exempt[key]
      ? `contract tests only: ${exempt[key]}`
      : "MISSING",
}));
const missing = rows.filter((row) => row.state === "MISSING");
const stale = Object.keys(exempt).filter((key) => success.has(key) || !keys.includes(key));

const lines = [
  "# Operation coverage",
  "",
  "Generated by `bun run coverage` from a run of the suites against the Python reference.",
  "",
  `- Operations in the contract: ${rows.length}`,
  `- With contract tests (routed, same answer as the reference to a bare request, 401 without a token, scope check): ${seen.size}`,
  `- With a success-path test: ${success.size}`,
  `- Contract tests only, with a stated reason: ${rows.length - success.size - missing.length}`,
  `- Missing: ${missing.length}`,
  "",
  "| Operation | Coverage |",
  "| --- | --- |",
  ...rows.map((row) => `| \`${row.key}\` | ${row.state} |`),
  "",
];
writeFileSync(join(import.meta.dir, "..", "COVERAGE.md"), lines.join("\n"));
console.log(lines.slice(4, 9).join("\n"));
if (missing.length)
  console.log(`\nNo success-path test and no exemption:\n${missing.map((row) => `  ${row.key}`).join("\n")}`);
if (stale.length)
  console.log(`\nExemptions that are no longer needed:\n${stale.map((key) => `  ${key}`).join("\n")}`);
if (missing.length || stale.length || seen.size !== rows.length) process.exit(1);
